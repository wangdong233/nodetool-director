/**
 * Appbuilder i18n — render-time resolution for the puck config's frozen labels.
 *
 * Puck reads `field.label` / `component.label` / select options from the config
 * object at RENDER time, but the module-level `appConfig` bakes its English
 * strings at import — a module-scope `i18n.t` would freeze English before the
 * lazy zh-CN bundles land (precedent: ADDABLE_EFFECTS, ui2 commit). So the
 * English→key table below is pure data (no `i18n.t` at module init) and every
 * consumer resolves `tAttr(...)` during render:
 *
 * - `localizeAppConfig` clones `appConfig` inside a `useMemo` keyed on a
 *   languageChanged revision (PuckAppEditor), swapping labels/options/titles.
 * - field pickers, panels, and widgets call `tAttr` at their render sites.
 *
 * The table doubles as the dead-key guard's evidence: every
 * `appbuilder:attrs.<key>` leaf appears here as an object-literal key in src.
 * `web/src/i18n/locales/{en,zh-CN}/appbuilder.json` is generated from it —
 * keep the three in sync (en values MUST equal the English source strings;
 * appbuilder/__tests__ asserts the table and the en catalog agree).
 */

