/** English string → key. Built once at import; pure data, no i18n calls. */
const KEY_BY_TEXT: ReadonlyMap<string, string> = new Map(
  Object.entries(APPBUILDER_ATTRS).map(([key, text]) => [text, key])
);

/**
 * Translate one appbuilder UI string at render time. Unknown strings (future
 * labels, author-edited values) fall through untouched, so the raw key string
 * never reaches the DOM and custom user content is never rewritten.
 */
export function tAttr(text: string): string {
  const key = KEY_BY_TEXT.get(text);
  if (!key) return text;
  return i18n.t(`appbuilder:attrs.${key}`, { defaultValue: text });
}

/**
 * Translate an interpolated appbuilder string by key (for labels composed
 * with runtime values — `output · {{label}}` and friends). The full
 * `appbuilder:attrs.<key>` literal in source keeps the dead-key guard green.
 */
export function tAttrTpl(
  key: string,
  english: string,
  vars: Record<string, string | number>
): string {
  return i18n.t(`appbuilder:attrs.${key}`, {
    defaultValue: english,
    ...vars
  });
}

/** Translate a list of `{label, value}` options at render time. */
export function tAttrOptions<T extends { label: string }>(options: readonly T[]): T[] {
  return options.map((option) =>
    option.label ? { ...option, label: tAttr(option.label) } : option
  );
}
